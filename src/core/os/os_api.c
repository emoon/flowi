// The public fl_os_* surface: each call forwards to the internal OS layer in os.h.

#include "os.h"

_Static_assert(sizeof(FlOsThread) == sizeof(Thread), "FlOsThread must match the internal Thread layout");

int64_t fl_os_time_us(void) {
    return get_current_time_us_os();
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

uint64_t fl_os_monotonic_ns(void) {
    return get_monotonic_time_ns_os();
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_os_sleep_us(uint64_t microseconds) {
    sleep_us(microseconds);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_os_sleep_ms(uint64_t milliseconds) {
    sleep_ms(milliseconds);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_os_thread_create(FlOsThread* thread, FlOsThreadFunc func, void* user_data) {
    return os_thread_create((Thread*)thread, func, user_data);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void* fl_os_thread_join(FlOsThread* thread) {
    return os_thread_join((Thread*)thread);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

uint32_t fl_os_process_id(void) {
    return get_process_id_os();
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

FlString fl_os_temp_directory(FlArena* arena) {
    return get_temp_directory_os(arena);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

const char* fl_os_getenv(const char* name) {
    return getenv_os(name);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_os_file_exists(FlString path) {
    return file_exists_os(path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_os_directory_exists(FlString path) {
    return file_directory_exists_os(path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int64_t fl_os_file_write(FlString path, const uint8_t* data, int64_t size) {
    return file_write_os(path, data, size);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int64_t fl_os_file_open_write(FlString path, bool append) {
    return file_open_write_os(path, append);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int64_t fl_os_file_write_to_handle(int64_t fd, const uint8_t* data, int64_t size) {
    return file_write_to_handle_os(fd, data, size);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_os_file_close_handle(int64_t fd) {
    file_close_handle_os(fd);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_os_file_delete(FlString path) {
    file_delete_os(path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_os_create_directory(FlString path) {
    return file_create_directory_os(path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_os_create_directory_recursive(FlString path) {
    return file_create_directory_recursive_os(path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_os_remove_directory_recursive(FlString path) {
    return file_remove_directory_recursive_os(path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

FlString fl_os_build_path(FlArena* arena, FlString base_path, FlString relative_path) {
    return file_build_path_os(arena, base_path, relative_path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

FlOsDir fl_os_dir_open(FlArena* arena, FlString path) {
    return dir_open_os(arena, path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

FlOsFileStat fl_os_dir_read_next(FlArena* arena, FlOsDir* dir) {
    return dir_read_next_os(arena, dir);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_os_dir_close(FlOsDir* dir) {
    dir_close_os(dir);
}
