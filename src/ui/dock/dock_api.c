// Dock API - hand-written bodies for the public fl_dock_* prototypes api_gen emits into flowi/ui/dock.h. Thin
// forwarders onto the internal docking API, resolving the active window's workspace via dock_workspace_current(),
// which always answers a workspace.

#include "dock_shared.h"
#include "dock_workspace.h"

#include <flowi/ui/dock.h> // generated fl_dock_* prototypes - the bodies below must match them

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_workspace_begin(void) {
    dock_workspace_begin(dock_workspace_current());
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_workspace_end(void) {
    dock_workspace_end(dock_workspace_current());
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_workspace_emit(void) {
    dock_workspace_emit(dock_workspace_current());
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_dock_panel(uint64_t id, FlString title) {
    return dock_panel_scope_begin(id, title);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_panel_end(void) {
    dock_panel_scope_end();
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_add_panel(uint64_t panel) {
    FlDockTree* tree = dock_workspace_current()->tree;
    FlDockRequest req = { .kind = FlDockRequest_Tab, .panel = panel, .target_node = tree->root->id };
    dock_tree_apply(tree, &req);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_dock_outer(uint64_t panel, FlDockSide side) {
    FlDockTree* tree = dock_workspace_current()->tree;
    FlDockRequest req = { .kind = FlDockRequest_Outer, .panel = panel, .side = side };
    dock_tree_apply(tree, &req);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_dock_outer_share(uint64_t panel, FlDockSide side, float share) {
    FlDockTree* tree = dock_workspace_current()->tree;
    FlDockRequest req = { .kind = FlDockRequest_Outer, .panel = panel, .side = side, .ratio = share };
    dock_tree_apply(tree, &req);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_promote_panel(uint64_t panel) {
    dock_promote_panel(panel); // resolves the current workspace itself
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_dock_panel_should_emit(uint64_t id) {
    return dock_workspace_panel_should_emit(dock_workspace_current(), id);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_set_panel_visible(uint64_t id, bool visible) {
    dock_workspace_set_panel_visible(dock_workspace_current(), id, visible);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_dock_panel_visible(uint64_t id) {
    return dock_workspace_panel_visible(dock_workspace_current(), id);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

uint32_t fl_dock_panel_leaf(uint64_t id) {
    return dock_workspace_panel_leaf(dock_workspace_current(), id);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

bool fl_dock_panel_reserved(uint64_t id) {
    return dock_workspace_panel_reserved(dock_workspace_current(), id);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_set_panel_family(uint64_t id, uint32_t family) {
    dock_workspace_set_panel_family(dock_workspace_current(), id, family);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

uint32_t fl_dock_panel_family(uint64_t id) {
    return dock_workspace_panel_family(dock_workspace_current(), id);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_set_family_filter(uint32_t family) {
    dock_workspace_current()->family_filter = family;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

uint32_t fl_dock_family_filter(void) {
    return dock_workspace_current()->family_filter;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

uint64_t fl_dock_active_panel(void) {
    return dock_workspace_current()->active_panel;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void fl_dock_set_active_panel(uint64_t id) {
    dock_workspace_set_active_panel(dock_workspace_current(), id);
}

