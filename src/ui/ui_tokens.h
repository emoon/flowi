#pragma once

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// UI Design Tokens - Internal Helpers
//
// Convenience macros over the design tokens generated into include/flowi/ui/ (re-exported via
// <ui/ui_types.h>). Based on an 8px base unit in logical (authoring) pixels.
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include <ui/ui_types.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Token-Based Padding Presets

#define fl_padding_md() padding_all(FlSpacing_MD)

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Directional Padding Helpers

// Combined horizontal and vertical padding
#define fl_padding_hv(h_spacing, v_spacing) \
    ((FlLayoutPadding) { (uint16_t)(h_spacing), (uint16_t)(h_spacing), (uint16_t)(v_spacing), (uint16_t)(v_spacing) })

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Corner Radius Helpers (Directional)

// Left corners only
#define fl_corner_radius_left(radius) ((FlCornerRadius) { (float)(radius), 0.0f, (float)(radius), 0.0f })

// Right corners only
#define fl_corner_radius_right(radius) ((FlCornerRadius) { 0.0f, (float)(radius), 0.0f, (float)(radius) })

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Token-Based Sizing Presets

#define fl_sizing_height_md() sizing_fixed(FlWidgetHeight_MD)
