// Standalone SDL + OpenGL window driving the GPU render backend: a static, labelled primitive gallery
// exercising the render-IR command set - solid + gradient fills, per-side borders, rect clips, real text
// (Roboto, embedded), a procedural image (color + tinted), arcs/rings, circles, diamonds, stroked + filled
// polylines, a batched bar set, embedded SVG vector icons, and effect annotations. Each frame builds the scene
// into a rewound arena, hands it to the GPU FlRenderBackend, grabs the offscreen UI texture through
// gpu_renderer_surface_texture(), and composites it over a cleared background with a fullscreen quad -
// premultiplied src-over, since the seam's texture carries premultiplied coverage alpha.
//
// Dev/hardware-only: the all-compute backend's SSBO reads abort on some software rasterizers, so this is not a
// CI gate. It needs a current GL >= 4.3 core context.
//
// Navigation: a pan/zoom view (offset + scale) is applied to the scene geometry as it is built - every
// coordinate, length, radius and stroke width is transformed before it reaches the IR - so the GPU backend
// re-rasterizes vector edges crisp at the current zoom. The compositor stays a plain 1:1 blit.
//
//   ./gpu_window_example           # left-drag pan, right-drag zoom, R reset, resize drives change_resolution, ESC
//   quits

