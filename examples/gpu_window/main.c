// Standalone SDL + OpenGL window driving the GPU render backend with a static, labelled gallery of the
// render-IR commands: solid and gradient fills, per-side borders, rect clips, text (embedded Roboto), a
// procedural image (color and tinted), arcs and rings, circles, diamonds, stroked and filled polylines, a
// batched bar set, embedded SVG icons and effects. Each frame builds the scene into a rewound arena, hands it
// to the GPU FlRenderBackend, takes the offscreen UI texture from gpu_renderer_surface_texture(), and
// composites it over a cleared background with a fullscreen quad. The blend is premultiplied src-over because
// the texture carries premultiplied coverage alpha.
//
// Not run in CI: the compute backend's SSBO reads abort on some software rasterizers. It needs a GL 4.3 core
// context.
//
// The pan/zoom view (offset + scale) is applied to the scene geometry as it is built, so every coordinate,
// length, radius and stroke width is transformed before it reaches the IR and the GPU backend rasterizes
// vector edges at the current zoom. The compositor is a 1:1 blit.
//
// Controls: left-drag pans, right-drag zooms, R resets the view, ESC quits. Resizing the window calls
// change_resolution.

