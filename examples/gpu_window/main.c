// Standalone SDL + OpenGL window driving the GPU render backend with a static, labelled gallery of the
// render-IR commands: solid and gradient fills, per-side borders, rect clips, text (embedded Roboto), a
// procedural image (color and tinted), arcs and rings, circles, diamonds, stroked and filled polylines, a
// batched bar set, embedded SVG icons and effects. Each frame builds the scene into a rewound arena, hands it
// to the GPU FlRenderBackend, takes the offscreen UI texture from gpu_renderer_surface_texture(), and
// composites it over a cleared background with a fullscreen quad. The blend is premultiplied src-over because
// the texture carries premultiplied coverage alpha.
//
// Not run in CI: the compute backend's SSBO reads abort on some software rasterizers. It needs a GL 4.3 core
// context.
//
// The pan/zoom view (offset + scale) is applied to the scene geometry as it is built, so every coordinate,
// length, radius and stroke width is transformed before it reaches the IR and the GPU backend rasterizes
// vector edges at the current zoom. The compositor is a 1:1 blit.
//
// Controls: left-drag pans, right-drag zooms, R resets the view, ESC quits. Resizing the window calls
// change_resolution.

#include "compositor.h"
#include "demo_assets.h"
#include "gallery.h"
#include "input.h"
#include <core/core.h>
#include <core/log.h>
#include <render/gpu/gpu_renderer.h>

#include "icon_color_svg.h"     // generated by CMake from assets/icon_color.svg
#include "icon_mono_svg.h"      // generated by CMake from assets/icon_mono.svg
#include "roboto_regular_ttf.h" // generated by CMake from examples/data/Roboto-Regular.ttf

#include <SDL2/SDL.h>
#include <stdbool.h>

#define WINDOW_SIZE 800

typedef struct App {
    FlArena* arena;
    SDL_Window* window;
    SDL_GLContext gl_ctx;
    Compositor compositor;
    FlRenderBackend backend;
    FlSurface* surface;
    FlFontCache* font_cache;
    FlArena* ir_arena;
    FlArena* glyph_arena;
    Gallery gallery;
} App;

static bool open_window(App* app) {
    if (SDL_Init(SDL_INIT_VIDEO) != 0) {
        log_error("SDL_Init failed: %s", SDL_GetError());
        return false;
    }

    // The backend resolves GL through eglGetProcAddress, so force an EGL-backed context on X11 too (Wayland
    // already uses EGL). GL 4.3 core is the backend's minimum.
    SDL_SetHint(SDL_HINT_VIDEO_X11_FORCE_EGL, "1");
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_MAJOR_VERSION, 4);
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_MINOR_VERSION, 3);
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_PROFILE_MASK, SDL_GL_CONTEXT_PROFILE_CORE);
    SDL_GL_SetAttribute(SDL_GL_DOUBLEBUFFER, 1);

    app->window = SDL_CreateWindow("flowi — GPU backend", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, WINDOW_SIZE,
                                   WINDOW_SIZE, SDL_WINDOW_OPENGL | SDL_WINDOW_RESIZABLE);
    if (app->window == nullptr) {
        log_error("SDL_CreateWindow failed: %s", SDL_GetError());
        return false;
    }

    app->gl_ctx = SDL_GL_CreateContext(app->window);
    if (app->gl_ctx == nullptr) {
        log_error("SDL_GL_CreateContext failed: %s", SDL_GetError());
        return false;
    }
    SDL_GL_SetSwapInterval(1); // vsync
    return true;
}

static bool create_backend(App* app) {
    if (!compositor_init(&app->compositor)) {
        return false;
    }

    // create_gpu_renderer needs the GL context to be current.
    app->backend = create_gpu_renderer(app->arena);
    if (app->backend.render == nullptr) {
        log_error("create_gpu_renderer failed — context below GL 4.3 or shader compile error");
        return false;
    }
    log_info("gpu_window example: GL context up, backend created at %dx%d", WINDOW_SIZE, WINDOW_SIZE);

    // render and change_resolution take a surface, so create one for this window.
    app->surface = app->backend.create_surface(app->backend.user_data, WINDOW_SIZE, WINDOW_SIZE);
    return true;
}

static FlFontId load_font(App* app) {
    // Embedded Roboto, loaded from memory, so the font is ready immediately.
    app->font_cache = font_cache_new(app->arena);
    // The load-time size is only a stored default. Every draw passes its own size, which the glyph outline and
    // advance lookups key on.
    FlFontId font
        = font_cache_load_font_memory(app->font_cache, k_roboto_regular_ttf, (i64)sizeof(k_roboto_regular_ttf), 16);
    if (app->backend.set_font_cache != nullptr) {
        app->backend.set_font_cache(app->backend.user_data, app->font_cache);
    }
    return font;
}

static void load_gallery(App* app, FlFontId font) {
    app->ir_arena = arena_new();
    app->glyph_arena = arena_new(); // text layout + outline scratch (must differ from ir_arena)

    // The procedural image lives in the backend's image atlas, which a resize does not touch, so prepare it once.
    const FlImageHandle demo_image = 1;
    prepare_demo_image(&app->backend, app->glyph_arena, demo_image);

    // SVG icons are parsed once into the process-lifetime arena. scene_svg hands the contours to prepare_vector
    // again on each zoom step, so they cannot live in the rewound ir_arena or glyph_arena. The handles differ
    // from the procedural image's.
    SvgIcon svg_mono = load_svg_icon(app->arena, SVG_SOURCE(k_icon_mono_svg, "icon_mono.svg"), 2);
    SvgIcon svg_color = load_svg_icon(app->arena, SVG_SOURCE(k_icon_color_svg, "icon_color.svg"), 3);

    app->gallery = (Gallery) {
        .painter = { .arena = app->ir_arena,
                     .scratch = app->glyph_arena,
                     .backend = &app->backend,
                     .font_cache = app->font_cache,
                     .font = font,
                     .view = { .zoom = 1.0f, .screen_w = (f32)WINDOW_SIZE, .screen_h = (f32)WINDOW_SIZE } },
        .image = demo_image,
        .svg_mono = svg_mono,
        .svg_color = svg_color,
    };
}

static bool app_init(App* app) {
    app->arena = fl_init(1);
    if (app->arena == nullptr) {
        log_error("fl_init failed");
        return false;
    }
    if (!open_window(app) || !create_backend(app)) {
        return false;
    }
    load_gallery(app, load_font(app));
    return true;
}

static void render_frame(App* app) {
    FlRenderFrame frame = {
        .global_alpha = 255,
    };
    gallery_build(&app->gallery, &frame);
    app->backend.render(app->backend.user_data, app->surface, &frame);

    GpuSurfaceTexture surf = gpu_renderer_surface_texture(app->surface);

    int draw_w = 0;
    int draw_h = 0;
    SDL_GL_GetDrawableSize(app->window, &draw_w, &draw_h);
    compositor_draw(&app->compositor, (GLuint)surf.handle, draw_w, draw_h);
    SDL_GL_SwapWindow(app->window);
}

static void resize_surface(App* app) {
    View* view = &app->gallery.painter.view;
    app->backend.change_resolution(app->backend.user_data, app->surface, (int)view->screen_w, (int)view->screen_h);
}

static bool drain_events(App* app, SDL_Event* event, bool* running) {
    bool dirty = false;
    do {
        InputOutcome outcome = input_apply(&app->gallery.painter.view, event);
        if (outcome.quit) {
            *running = false;
        }
        if (outcome.resized) {
            resize_surface(app);
        }
        dirty = dirty || outcome.redraw;
    } while (SDL_PollEvent(event));
    return dirty;
}

// The gallery is static, so it renders only when the view changes and the loop blocks on the event queue
// otherwise. dirty starts true to paint the first frame.
static void run(App* app) {
    bool running = true;
    bool dirty = true;
    while (running) {
        if (dirty) {
            render_frame(app);
            dirty = false;
        }

        // Block until the next event, then drain the whole queue before the next redraw. Only events that change
        // what is shown set dirty.
        SDL_Event event;
        if (!SDL_WaitEvent(&event)) {
            break; // event subsystem error
        }
        dirty = drain_events(app, &event, &running);
    }
}

static void shutdown_app(App* app) {
    fl_arena_destroy(app->glyph_arena);
    fl_arena_destroy(app->ir_arena);
    font_cache_destroy(app->font_cache);
    app->backend.destroy_surface(app->backend.user_data, app->surface);
    app->backend.destroy(app->backend.user_data);
    SDL_GL_DeleteContext(app->gl_ctx);
    SDL_DestroyWindow(app->window);
    SDL_Quit();
}

int main(void) {
    App app = { 0 };
    if (!app_init(&app)) {
        return 1;
    }
    run(&app);
    shutdown_app(&app);
    return 0;
}
