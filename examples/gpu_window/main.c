// Text helper: prepare each on-screen glyph's atlas entry, then emit the run. Glyph prep is keyed by codepoint
// to match fl_ir_text_layout's FlGlyph.glyph_id, but the outline is fetched by face glyph index (FT_Load_Glyph
// wants an index, not a codepoint). scratch MUST be a different arena than the IR arena.

// size_world is the 1:1 font size. A glyph's pixel size must be integral and so cannot follow the zoom
// continuously by re-rastering alone, so crisp-under-zoom text rests on two decouplings:
//
//  1. Raster size vs display size. Glyphs rasterize (and the atlas keys) at raster - the zoomed size snapped
//     to font_cache's quantization grid, so it changes only in discrete steps (quantize is idempotent, so
//     preparing at it hits no further rounding). The run carries scale = display / raster, and the backend
//     scales each glyph quad by it.
//
//  2. Layout vs raster. The run is laid out in world space at a stable metrics size and the view scales the pen
//     positions by zoom, exactly like every other primitive. Advancing the pen at raster instead would step
//     spacing with it: hinting makes the advance-per-pixel non-constant across sizes, and that error
//     accumulates along the run.
static void draw_text(FlArena* arena, FlArena* scratch, FlRenderBackend* backend, FlFontCache* fc, FlFontId font,
                      View v, f32 size_world, FlColor color, FlString text, f32 x, f32 baseline_y) {
    f32 display = size_world * v.zoom;
    if (display < 1.0f) {
        display = 1.0f;
    }
    u16 raster = font_cache_quantize_size((u16)(display + 0.5f));
    if (raster < 1) {
        raster = 1;
    }
    // The quarter-px key the outline/atlas/run ride. raster is already bucket-quantized above, so form the
    // key directly rather than via font_cache_whole_px_to_q4 (which would re-bucket the band boundaries).
    u16 raster_q4 = font_cache_quantize_size_q4((f32)raster);
    f32 scale = display / (f32)raster;
    u16 metrics = (u16)(size_world + 0.5f);
    if (metrics < 1) {
        metrics = 1;
    }

    // Cull per glyph against the visible world region: keep a glyph iff its pen point is within one em of the
    // viewport. A glyph's ink stays within ~one em of its pen in every direction (ascent/descent, left side
    // bearing, advance) for the Latin faces this gallery uses, so an em of margin admits any glyph that reaches
    // the window without edge pop-in. Skipping off-screen glyphs here is what keeps the atlas to the visible
    // working set: without it the whole gallery's text rasterizes at the zoomed pixel size and overflows the
    // packer, dropping glyphs.
    f32 margin = size_world;

    if (backend->prepare_glyph != NULL) {
        f32 world_x = x;
        Utf8Iter it = utf8_iter(text);
        while (!utf8_iter_done(&it)) {
            u32 codepoint = utf8_iter_next(&it);
            if (codepoint == 0) {
                break;
            }
            FlRect pen = { world_x, baseline_y, 0.0f, 0.0f };
            if (view_visible(v, pen, margin)) {
                fl_arena_rewind(scratch);
                u32 glyph_index = font_cache_get_glyph_index(fc, font, codepoint);
                FlGlyphOutline outline;
                if (font_cache_get_glyph_outline(fc, font, raster_q4, glyph_index, scratch, &outline)) {
                    backend->prepare_glyph(backend->user_data, font, raster_q4, codepoint, &outline);
                }
            }
            world_x += (f32)font_cache_get_glyph_advance(fc, font, metrics, codepoint) / 64.0f;
        }
    }

    // Lay out in world space (pen advances at the stable metrics size), placing each glyph at its view-mapped
    // screen position. This is fl_ir_text_layout's loop, but with the advance size decoupled from the run's
    // raster size - the one thing that builder can't express. Off-screen glyphs are dropped here too, matching
    // the prepare pass so the run only references atlas cells that exist.
    fl_arena_rewind(scratch);
    FlGlyph* glyphs = arena_pos_type(scratch, FlGlyph);
    u32 count = 0;
    f32 world_x = x;
    Utf8Iter it = utf8_iter(text);
    while (!utf8_iter_done(&it)) {
        u32 codepoint = utf8_iter_next(&it);
        if (codepoint == 0) {
            break;
        }
        FlRect pen = { world_x, baseline_y, 0.0f, 0.0f };
        if (view_visible(v, pen, margin)) {
            FlGlyph* eg = arena_alloc(scratch, FlGlyph);
            eg->glyph_id = codepoint;
            eg->x = v_x(v, world_x);
            eg->y = v_y(v, baseline_y);
            count++;
        }
        world_x += (f32)font_cache_get_glyph_advance(fc, font, metrics, codepoint) / 64.0f;
    }
    if (count > 0) {
        fl_ir_text_run(arena, font, raster_q4, scale, color, glyphs, count);
    }
}

// A parsed SVG icon bound to the backend handle its prepared atlas cell is keyed under.
typedef struct SvgIcon {
    const FlVectorImage* image; // resolution-independent contours (NULL if parse failed)
    FlImageHandle handle;
} SvgIcon;

// Draw an SVG vector icon, crisp under zoom - the SVG analog of draw_text. The backend (re)rasterizes the
// shared vector layer's contours into its zoom-regenerated SVG atlas keyed by (handle, quantized size), so
// exactly like glyphs this re-prepares every frame at the size the physical (zoomed) dst needs:
// svg_raster_size_for_dst quantizes, and prepare_vector short-circuits unless a quantized step is crossed.
// Monochrome icons resolve to tintable coverage; multi-color ones to baked RGBA, tint ignored. A NULL image
// (parse failure) no-ops.
static void draw_svg(FlArena* arena, FlRenderBackend* backend, View v, SvgIcon icon, FlRect dst_world, FlColor tint) {
    if (icon.image == NULL) {
        return;
    }
    if (backend->prepare_vector != NULL) {
        u16 size = svg_raster_size_for_dst(v_len(v, dst_world.w), v_len(v, dst_world.h), icon.image->classification);
        backend->prepare_vector(backend->user_data, icon.handle, size, icon.image);
    }
    vw_image(arena, v, (FlImageSource) { .kind = FlImageKind_Static, .handle = icon.handle }, FlImageMode_Color,
             dst_world, (FlRect) { 0 }, tint, FlImageFilter_Linear);
}

// A faint panel + label backing every gallery cell.
static void draw_cell_chrome(FlArena* arena, FlArena* scratch, FlRenderBackend* backend, FlFontCache* fc, FlFontId font,
                             View v, FlRect cell, FlString label) {
    vw_fill_rect(arena, v, cell, (FlCornerRadius) { 8, 8, 8, 8 }, (FlColor[4]) { k_panel, k_panel, k_panel, k_panel });
    vw_border(arena, v, cell, 1, 1, 1, 1, (FlCornerRadius) { 8, 8, 8, 8 }, k_panel_border);
    draw_text(arena, scratch, backend, fc, font, v, LABEL_SIZE, k_dim, label, cell.x + 12.0f, cell.y + cell.h - 12.0f);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// The gallery scene, rebuilt into a rewound arena every frame (static - no animation).

static void build_scene(FlArena* arena, FlArena* scratch, FlRenderBackend* backend, FlFontCache* fc, FlFontId font,
                        FlImageHandle image, SvgIcon svg_mono, SvgIcon svg_color, View v, const void** out_commands,
                        size_t* out_bytes, int width, int height) {
    fl_arena_rewind(arena);
    fl_arena_align(arena, 8);
    const void* start = fl_arena_current_pos(arena);

    // Full-window background - emitted in screen space (NOT view-transformed) so a stable backdrop always fills
    // the window while the gallery pans/zooms over it.
    fl_ir_fill_rect(arena, (FlRect) { 0, 0, (f32)width, (f32)height }, (FlCornerRadius) { 0 },
                    (FlColor[4]) { k_bg, k_bg, k_bg, k_bg }, nullptr);

    draw_text(arena, scratch, backend, fc, font, v, TITLE_SIZE, k_ink, FL_S("flowi — GPU backend primitive gallery"),
              MARGIN, MARGIN + 26.0f);

    {
        FlRect c = cell_rect(0, 0);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("fill + gradient"));
        vw_fill_rect(arena, v, (FlRect) { c.x + 16, c.y + 16, 90, 90 }, (FlCornerRadius) { 14, 14, 14, 14 },
                     (FlColor[4]) { k_accent, k_accent, k_accent, k_accent });
        const FlColor tl = { 220, 80, 80, 255 };
        const FlColor tr = { 80, 220, 120, 255 };
        const FlColor bl = { 80, 120, 220, 255 };
        const FlColor br = { 220, 200, 80, 255 };
        vw_fill_rect(arena, v, (FlRect) { c.x + 128, c.y + 16, 90, 90 }, (FlCornerRadius) { 0 },
                     (FlColor[4]) { tl, tr, bl, br });
    }

    {
        FlRect c = cell_rect(1, 0);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("borders"));
        FlRect a = { c.x + 16, c.y + 16, 90, 90 };
        vw_fill_rect(arena, v, a, (FlCornerRadius) { 12, 12, 12, 12 },
                     (FlColor[4]) { k_panel, k_panel, k_panel, k_panel });
        vw_border(arena, v, a, 3, 3, 3, 3, (FlCornerRadius) { 12, 12, 12, 12 }, k_accent);
        FlRect b = { c.x + 128, c.y + 16, 90, 90 };
        vw_fill_rect(arena, v, b, (FlCornerRadius) { 0 }, (FlColor[4]) { k_panel, k_panel, k_panel, k_panel });
        vw_border(arena, v, b, 8, 2, 2, 8, (FlCornerRadius) { 0 }, k_warn); // thick left/bottom, thin right/top
    }

    {
        FlRect c = cell_rect(2, 0);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("clip"));
        fl_ir_clip_push(arena, v_rect(v, (FlRect) { c.x + 16, c.y + 16, 120, 70 }));
        vw_fill_rect(arena, v, (FlRect) { c.x + 60, c.y + 8, 140, 110 }, (FlCornerRadius) { 0 },
                     (FlColor[4]) { k_green, k_green, k_green, k_green });
        fl_ir_clip_pop(arena);
    }

    {
        FlRect c = cell_rect(0, 1);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("circle + diamond"));
        vw_circle(arena, v, c.x + 62, c.y + 58, 36, k_accent, k_white, 3);
        vw_diamond(arena, v, c.x + 168, c.y + 58, 36, 46, k_warn, k_white, 3);
    }

    {
        FlRect c = cell_rect(1, 1);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("arc / ring / sector"));
        f32 cy = c.y + 58;
        vw_arc(arena, v, c.x + 50, cy, 34, 7, 0.0f, 6.2831853f, k_accent, 0);                // full ring
        vw_arc(arena, v, c.x + 125, cy, 34, 16, 0.2f, 4.2f, k_green, FlArcFlags_round_caps); // capped sweep
        vw_arc(arena, v, c.x + 200, cy, 34, 40, 0.0f, 2.3f, k_warn, 0);                      // filled sector
    }

    {
        FlRect c = cell_rect(2, 1);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("polyline (stroked + filled)"));
        enum { N = 48 };
        f32 x0 = c.x + 14;
        f32 span = CELL_W - 28.0f;
        f32 mid = c.y + 50;
        FlPolyPoint* stroke = fl_ir_polyline(arena, k_accent, k_accent, v_len(v, 2.5f), v_y(v, mid), 0, N, NULL);
        for (int i = 0; i < N; i++) {
            f32 t = (f32)i / (f32)(N - 1);
            stroke[i] = (FlPolyPoint) { v_x(v, x0 + t * span), v_y(v, mid - 22.0f * sinf(t * 6.2831853f)), 1.0f };
        }
        f32 base = c.y + 124;
        FlPolyPoint* fill
            = fl_ir_polyline(arena, k_green, k_green, v_len(v, 1.5f), v_y(v, base), FlPolylineFlags_filled, N, NULL);
        for (int i = 0; i < N; i++) {
            f32 t = (f32)i / (f32)(N - 1);
            fill[i]
                = (FlPolyPoint) { v_x(v, x0 + t * span), v_y(v, base - 30.0f * (0.5f + 0.5f * sinf(t * 9.4f))), 1.0f };
        }
    }

    {
        FlRect c = cell_rect(0, 2);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("bars (batched)"));
        enum { N = 14 };
        f32 base = c.y + 128; // bars grow upward from a baseline near the cell's bottom
        f32 bw = 12.0f;
        f32 gap = 4.0f;
        f32 x0 = c.x + 16;
        FlBar* bars = fl_ir_bars(arena, v_y(v, base), k_accent, N, NULL);
        for (int i = 0; i < N; i++) {
            f32 t = (f32)i / (f32)(N - 1);
            f32 h = 20.0f + 70.0f * (0.5f + 0.5f * sinf(t * 7.0f));
            bars[i] = (FlBar) { v_x(v, x0 + (f32)i * (bw + gap)), v_len(v, bw), v_len(v, h) };
        }
    }

    {
        FlRect c = cell_rect(1, 2);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("image (color + tint)"));
        FlImageSource src = { .kind = FlImageKind_Static, .handle = image };
        vw_image(arena, v, src, FlImageMode_Color, (FlRect) { c.x + 16, c.y + 16, 90, 90 }, (FlRect) { 0 }, k_white,
                 FlImageFilter_Nearest);
        vw_image(arena, v, src, FlImageMode_Color, (FlRect) { c.x + 128, c.y + 16, 90, 90 }, (FlRect) { 0 },
                 (FlColor) { 220, 150, 90, 255 }, FlImageFilter_Linear);
    }

    {
        FlRect c = cell_rect(2, 2);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("text (Roboto)"));
        draw_text(arena, scratch, backend, fc, font, v, 22, k_ink, FL_S("Sphinx of black quartz,"), c.x + 14, c.y + 38);
        draw_text(arena, scratch, backend, fc, font, v, 16, k_dim, FL_S("judge my vow. 0123456789"), c.x + 14,
                  c.y + 66);
        draw_text(arena, scratch, backend, fc, font, v, 14, k_green, FL_S("The quick brown fox jumps"), c.x + 14,
                  c.y + 92);
    }

    {
        FlRect c = cell_rect(0, 3);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("svg (mono, tinted)"));
        // White (identity) tint draws the icon's authored fill; any other tint recolors the coverage.
        draw_svg(arena, backend, v, svg_mono, (FlRect) { c.x + 24, c.y + 22, 80, 80 }, k_white);
        draw_svg(arena, backend, v, svg_mono, (FlRect) { c.x + 136, c.y + 22, 80, 80 }, k_warn);
    }

    {
        FlRect c = cell_rect(1, 3);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("svg (multi-color)"));
        draw_svg(arena, backend, v, svg_color, (FlRect) { c.x + 80, c.y + 20, 90, 90 }, k_white);
    }

    {
        FlRect c = cell_rect(2, 3);
        draw_cell_chrome(arena, scratch, backend, fc, font, v, c, FL_S("effects (shadow + glow)"));
        // The vw_* wrappers don't expose the builder's effect param, so call fl_ir_* directly. Offsets and
        // blur are world units scaled by zoom, so the shadow/glow track their shape under zoom.
        FlEffect drop = { .kind = FlEffectKind_DropShadow,
                          .color = { 0, 0, 0, 150 },
                          .off_x = v_len(v, 6),
                          .off_y = v_len(v, 7),
                          .blur = v_len(v, 5) };
        fl_ir_circle(arena, v_x(v, c.x + 62), v_y(v, c.y + 58), v_len(v, 32), k_accent, k_white, v_len(v, 2), &drop);
        FlEffect glow = { .kind = FlEffectKind_Glow, .color = { 120, 200, 120, 220 }, .blur = v_len(v, 9) };
        fl_ir_diamond(arena, v_x(v, c.x + 168), v_y(v, c.y + 58), v_len(v, 34), v_len(v, 44), k_green, k_white,
                      v_len(v, 2), &glow);
    }

    *out_commands = start;
    *out_bytes = (size_t)((const u8*)fl_arena_current_pos(arena) - (const u8*)start);
}

