#define MARGIN 16.0f
#define TITLE_H 40.0f
#define CELL_W 250.0f
#define CELL_H 160.0f
#define CELL_GAP 12.0f
#define LABEL_SIZE 14
#define TITLE_SIZE 24

static FlRect cell_rect(int col, int row) {
    return (FlRect) {
        MARGIN + (f32)col * (CELL_W + CELL_GAP),
        MARGIN + TITLE_H + (f32)row * (CELL_H + CELL_GAP),
        CELL_W,
        CELL_H,
    };
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// View: pan (pixels) + zoom, mapping authoring/world coordinates to screen as screen = world * zoom + pan. The
// transform is applied to every coordinate and size as the scene is built. Angles are scale-invariant and
// pass through untouched; the procedural image's source sub-rect is in texel space and is never transformed.

typedef struct View {
    f32 zoom;
    f32 pan_x;
    f32 pan_y;
    f32 screen_w; // window size in pixels
    f32 screen_h;
} View;

// World-space rectangle the window currently shows: the inverse of the view transform applied to the full
// window rect (screen = world*zoom + pan  =>  world = (screen - pan)/zoom).
static inline FlRect view_world_viewport(View v) {
    return (FlRect) { -v.pan_x / v.zoom, -v.pan_y / v.zoom, v.screen_w / v.zoom, v.screen_h / v.zoom };
}

// Is a world-space AABB at all on screen? margin_world pads the test so a primitive whose origin sits just
// off-screen but whose body reaches in is still kept.
static inline bool view_visible(View v, FlRect world, f32 margin_world) {
    FlRect vp = view_world_viewport(v);
    return !(world.x + world.w < vp.x - margin_world || world.x > vp.x + vp.w + margin_world
             || world.y + world.h < vp.y - margin_world || world.y > vp.y + vp.h + margin_world);
}

static inline f32 v_x(View v, f32 x) {
    return x * v.zoom + v.pan_x;
}
static inline f32 v_y(View v, f32 y) {
    return y * v.zoom + v.pan_y;
}
static inline f32 v_len(View v, f32 l) {
    return l * v.zoom;
}
static inline FlRect v_rect(View v, FlRect r) {
    return (FlRect) { r.x * v.zoom + v.pan_x, r.y * v.zoom + v.pan_y, r.w * v.zoom, r.h * v.zoom };
}
static inline FlCornerRadius v_radius(View v, FlCornerRadius c) {
    return (FlCornerRadius) { c.tl * v.zoom, c.tr * v.zoom, c.bl * v.zoom, c.br * v.zoom };
}

static void vw_fill_rect(FlArena* a, View v, FlRect r, FlCornerRadius cr, const FlColor corners[4]) {
    fl_ir_fill_rect(a, v_rect(v, r), v_radius(v, cr), corners, nullptr);
}
static void vw_border(FlArena* a, View v, FlRect r, f32 wl, f32 wr, f32 wt, f32 wb, FlCornerRadius cr, FlColor col) {
    fl_ir_border(a, v_rect(v, r), v_len(v, wl), v_len(v, wr), v_len(v, wt), v_len(v, wb), v_radius(v, cr), col);
}
static void vw_circle(FlArena* a, View v, f32 cx, f32 cy, f32 radius, FlColor col, FlColor bcol, f32 bw) {
    fl_ir_circle(a, v_x(v, cx), v_y(v, cy), v_len(v, radius), col, bcol, v_len(v, bw), NULL);
}
static void vw_diamond(FlArena* a, View v, f32 cx, f32 cy, f32 rx, f32 ry, FlColor col, FlColor bcol, f32 bw) {
    fl_ir_diamond(a, v_x(v, cx), v_y(v, cy), v_len(v, rx), v_len(v, ry), col, bcol, v_len(v, bw), NULL);
}
static void vw_arc(FlArena* a, View v, f32 cx, f32 cy, f32 radius, f32 thick, f32 start, f32 sweep, FlColor col,
                   u32 flags) {
    fl_ir_arc(a, v_x(v, cx), v_y(v, cy), v_len(v, radius), v_len(v, thick), start, sweep, col, flags, NULL);
}
static void vw_image(FlArena* a, View v, FlImageSource src, FlImageMode mode, FlRect dst, FlRect src_rect, FlColor tint,
                     FlImageFilter filter) {
    fl_ir_image(a, src, mode, v_rect(v, dst), src_rect, tint, filter, nullptr);
}

