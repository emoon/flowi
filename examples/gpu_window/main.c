// Build a small procedural RGBA image and hand it to the backend's prepare_image seam under handle. Opaque,
// so premultiplied == straight. The GPU backend keys the static image slot on the request id, so we pass
// handle as the request id and reference it as a kind-0 source.

static void prepare_demo_image(FlRenderBackend* backend, FlArena* scratch, FlImageHandle handle) {
    if (backend->prepare_image == NULL) {
        return;
    }
    enum { W = 32, H = 32 };
    static u8 pixels[W * H * 4];
    for (int y = 0; y < H; y++) {
        for (int x = 0; x < W; x++) {
            u8* px = &pixels[(y * W + x) * 4];
            bool checker = (((x >> 3) ^ (y >> 3)) & 1) != 0;
            px[0] = checker ? (u8)(80 + x * 4) : 40;
            px[1] = (u8)(40 + y * 5);
            px[2] = checker ? 90 : (u8)(150 + x * 2);
            px[3] = 255;
        }
    }
    FlImageDecodeResult decoded = {
        .pixels = pixels,
        .width = W,
        .height = H,
        .stride = W * 4,
        .channels = 4,
        .premultiplied = true,
    };
    FlImageLoadRequest request = { .relative_path = FL_S("procedural") };
    backend->prepare_image(backend->user_data, (FlImageLoadRequestId)handle, &decoded, scratch, &request);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main(void) {
    FlArena* arena = fl_init(1);
    if (arena == NULL) {
        log_error("fl_init failed");
        return 1;
    }

    if (SDL_Init(SDL_INIT_VIDEO) != 0) {
        log_error("SDL_Init failed: %s", SDL_GetError());
        return 1;
    }

    // The backend resolves GL through eglGetProcAddress, so force an EGL-backed context on X11 too (Wayland
    // already uses EGL). Request a GL 4.3 core context - the backend's floor.
    SDL_SetHint(SDL_HINT_VIDEO_X11_FORCE_EGL, "1");
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_MAJOR_VERSION, 4);
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_MINOR_VERSION, 3);
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_PROFILE_MASK, SDL_GL_CONTEXT_PROFILE_CORE);
    SDL_GL_SetAttribute(SDL_GL_DOUBLEBUFFER, 1);

    int width = 800;
    int height = 800;
    SDL_Window* window = SDL_CreateWindow("flowi — GPU backend", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, width,
                                          height, SDL_WINDOW_OPENGL | SDL_WINDOW_RESIZABLE);
    if (window == NULL) {
        log_error("SDL_CreateWindow failed: %s", SDL_GetError());
        return 1;
    }

    SDL_GLContext gl_ctx = SDL_GL_CreateContext(window);
    if (gl_ctx == NULL) {
        log_error("SDL_GL_CreateContext failed: %s", SDL_GetError());
        return 1;
    }
    SDL_GL_SetSwapInterval(1); // vsync

    CompositorGl gl;
    if (!compositor_gl_load(&gl)) {
        return 1;
    }
    GLuint program = build_compositor_program(&gl);
    if (program == 0) {
        return 1;
    }
    GLuint vao = 0;
    gl.GenVertexArrays(1, &vao); // core profile needs a bound VAO to draw, even with no attributes

    // Construct the GPU backend against the now-current context.
    FlRenderBackend backend = create_gpu_renderer(arena);
    if (backend.render == NULL) {
        log_error("create_gpu_renderer failed — context below GL 4.3 or shader compile error");
        return 1;
    }
    log_info("gpu_window example: GL context up, backend created at %dx%d", width, height);

    // Create this window's render surface - render / change_resolution are surface-scoped.
    FlSurface* surface = backend.create_surface(backend.user_data, width, height);

    // Font: embedded Roboto, loaded from memory (synchronous - ready immediately, no VFS round trip).
    FlFontCache* font_cache = font_cache_new(arena);
    // The load-time size is only a stored default; every draw passes its own size, which is what the glyph
    // outline/advance lookups key on.
    FlFontId font
        = font_cache_load_font_memory(font_cache, k_roboto_regular_ttf, (i64)sizeof(k_roboto_regular_ttf), 16);
    if (backend.set_font_cache != NULL) {
        backend.set_font_cache(backend.user_data, font_cache);
    }

    FlArena* ir_arena = arena_new();
    FlArena* glyph_arena = arena_new(); // text layout + outline scratch (must differ from ir_arena)

    // Procedural image lives in the backend's image atlas (untouched by resize); prepare it once.
    const FlImageHandle demo_image = 1;
    prepare_demo_image(&backend, glyph_arena, demo_image);

    // SVG icons: parsed once into the process-lifetime arena. The shared vector layer's contours must outlive
    // every frame - they are re-handed to prepare_vector on each zoom step (draw_svg) - so they cannot live in
    // the rewound ir_arena/glyph_arena. Handles are distinct from the procedural image's.
    SvgIcon svg_mono = { .handle = 2 };
    SvgIcon svg_color = { .handle = 3 };
    FlVectorImage* mono = arena_alloc(arena, FlVectorImage);
    if (vector_image_parse(k_icon_mono_svg, sizeof(k_icon_mono_svg), arena, mono)) {
        svg_mono.image = mono;
    } else {
        log_error("icon_mono.svg failed to parse");
    }
    FlVectorImage* color = arena_alloc(arena, FlVectorImage);
    if (vector_image_parse(k_icon_color_svg, sizeof(k_icon_color_svg), arena, color)) {
        svg_color.image = color;
    } else {
        log_error("icon_color.svg failed to parse");
    }

    // Scene view: pan in screen pixels + zoom, fed into build_scene's geometry transform (screen = world*zoom +
    // pan). Mutated by mouse drags; left-drag pans, right-drag zooms anchored at the cursor.
    f32 pan_x = 0.0f;
    f32 pan_y = 0.0f;
    f32 zoom = 1.0f;

    // Redraw-on-demand: the gallery is static, so it is rendered only when the view actually changes and the
    // loop blocks on the event queue otherwise. dirty starts true to paint the first frame.
    bool running = true;
    bool dirty = true;
    while (running) {
        if (dirty) {
            FlRenderFrame frame = {
                .global_alpha = 255,
            };
            View view
                = { .zoom = zoom, .pan_x = pan_x, .pan_y = pan_y, .screen_w = (f32)width, .screen_h = (f32)height };
            build_scene(ir_arena, glyph_arena, &backend, font_cache, font, demo_image, svg_mono, svg_color, view,
                        &frame.commands, &frame.bytes, width, height);
            backend.render(backend.user_data, surface, &frame);

            GpuSurfaceTexture surf = gpu_renderer_surface_texture(surface);

            int draw_w = 0;
            int draw_h = 0;
            SDL_GL_GetDrawableSize(window, &draw_w, &draw_h);
            glViewport(0, 0, draw_w, draw_h);
            glClearColor(0.06f, 0.06f, 0.08f, 1.0f);
            glClear(GL_COLOR_BUFFER_BIT);

            glEnable(GL_BLEND);
            glBlendFunc(GL_ONE, GL_ONE_MINUS_SRC_ALPHA); // premultiplied src-over (seam texture is premultiplied)

            gl.ActiveTexture(GL_TEXTURE0);
            glBindTexture(GL_TEXTURE_2D, (GLuint)surf.handle);
            // The backend's target is immutable single-level storage with no sampler filter set; the blit is 1:1
            // (the zoom lives in the scene geometry, not here), so NEAREST keeps it crisp and avoids a
            // mipmap-incomplete sample.
            glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
            glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);

            gl.UseProgram(program);
            gl.Uniform1i(gl.GetUniformLocation(program, "ui_tex"), 0);
            gl.BindVertexArray(vao);
            glDrawArrays(GL_TRIANGLES, 0, 3);

            glDisable(GL_BLEND);
            SDL_GL_SwapWindow(window);
            dirty = false;
        }

        // Block until the next event (idle = no CPU), then drain the whole queue before the next redraw. Only
        // events that change what is shown set dirty.
        SDL_Event event;
        if (!SDL_WaitEvent(&event)) {
            break; // event subsystem error - exit cleanly
        }
        do {
            if (event.type == SDL_QUIT) {
                running = false;
            } else if (event.type == SDL_KEYDOWN && event.key.keysym.sym == SDLK_ESCAPE) {
                running = false;
            } else if (event.type == SDL_KEYDOWN && event.key.keysym.sym == SDLK_r) {
                pan_x = 0.0f;
                pan_y = 0.0f;
                zoom = 1.0f;
                dirty = true;
            } else if (event.type == SDL_MOUSEMOTION) {
                // The held buttons ride on the motion event itself, so a missed button-up can't strand a drag
                // "on" (the cause of an idle redraw storm).
                if ((event.motion.state & SDL_BUTTON_LMASK) != 0) {
                    // screen = world * zoom + pan, so dragging the cursor shifts the content the same pixels.
                    pan_x += (f32)event.motion.xrel;
                    pan_y += (f32)event.motion.yrel;
                    dirty = true;
                } else if ((event.motion.state & SDL_BUTTON_RMASK) != 0) {
                    // Vertical drag scales zoom; keep the world point under the cursor fixed (anchor the zoom).
                    f32 z0 = zoom;
                    f32 z1 = z0 * expf(-(f32)event.motion.yrel * 0.01f);
                    z1 = z1 < 0.1f ? 0.1f : (z1 > 40.0f ? 40.0f : z1);
                    f32 cx = (f32)event.motion.x;
                    f32 cy = (f32)event.motion.y;
                    pan_x = cx - (cx - pan_x) * (z1 / z0);
                    pan_y = cy - (cy - pan_y) * (z1 / z0);
                    zoom = z1;
                    dirty = true;
                }
            } else if (event.type == SDL_WINDOWEVENT) {
                // Repaint only on a real size change or an expose; ignore the rest (focus, enter/leave, moves)
                // so a stationary window stays asleep.
                if (event.window.event == SDL_WINDOWEVENT_SIZE_CHANGED
                    && (event.window.data1 != width || event.window.data2 != height)) {
                    width = event.window.data1;
                    height = event.window.data2;
                    backend.change_resolution(backend.user_data, surface, width, height);
                    dirty = true;
                } else if (event.window.event == SDL_WINDOWEVENT_EXPOSED) {
                    dirty = true;
                }
            }
        } while (SDL_PollEvent(&event));
    }

    fl_arena_destroy(glyph_arena);
    fl_arena_destroy(ir_arena);
    font_cache_destroy(font_cache);
    backend.destroy_surface(backend.user_data, surface);
    backend.destroy(backend.user_data);
    SDL_GL_DeleteContext(gl_ctx);
    SDL_DestroyWindow(window);
    SDL_Quit();
    return 0;
}
